// Solves tic-tac-toe once and writes the answers into a source file, between its
// "BEGIN TABLE" and "END TABLE" markers. Run from this folder:
//
//   dotnet run GenTable.cs                                                      (TicTacToeTable.cs)
//   dotnet run GenTable.cs ../assembly-x64-lookup-table/TicTacToeTable.asm      (the assembly version)
//   dotnet run GenTable.cs ../assembly-x64-state-machine/TicTacToeStates.asm --state-machine
//
// The file's extension picks the output format: C# for anything else, MASM data for .asm.
// --state-machine writes the game as numbered states instead of a table of positions.
//
// The table has one entry for every position the computer can be asked to move in, counting only
// positions reached when the computer itself always plays a best move. Each entry packs the
// position and the set of best moves into one uint: (human | computer << 9) << 9 | bestMoves.
// "Best" uses the same scoring as the other versions (a win k plies away is worth 10 - k), so the
// moves are the same ones they would choose.
using System.Text;
using System.Text.RegularExpressions;

const int Full = 0x1FF;
int[] lines = [0b000_000_111, 0b000_111_000, 0b111_000_000,
               0b001_001_001, 0b010_010_010, 0b100_100_100,
               0b100_010_001, 0b001_010_100];

bool Wins(int mask) => lines.Any(line => (mask & line) == line);

var values = new Dictionary<int, int>();

// Value of the position for the side to move (mover); other just moved.
int Value(int mover, int other)
{
    if (Wins(other)) return -10;
    if ((mover | other) == Full) return 0;
    int key = mover | other << 9;
    if (values.TryGetValue(key, out int cached)) return cached;
    int best = -11;
    for (int bit = 1; bit <= Full; bit <<= 1)
        if (((mover | other) & bit) == 0)
            best = Math.Max(best, Toward(-Value(other, mover | bit)));
    return values[key] = best;
}

int Toward(int score) => score > 0 ? score - 1 : score < 0 ? score + 1 : 0;

var table = new SortedDictionary<int, int>();   // position key -> bitboard of best moves

void ComputerTurn(int human, int computer)
{
    int key = human | computer << 9;
    if (table.ContainsKey(key)) return;

    var scores = new Dictionary<int, int>();
    for (int bit = 1; bit <= Full; bit <<= 1)
        if (((human | computer) & bit) == 0)
            scores[bit] = Toward(-Value(human, computer | bit));
    int top = scores.Values.Max();
    int bestMoves = scores.Where(s => s.Value == top).Aggregate(0, (mask, s) => mask | s.Key);
    table[key] = bestMoves;

    for (int bit = 1; bit <= Full; bit <<= 1)
    {
        if ((bestMoves & bit) == 0) continue;
        int after = computer | bit;
        if (!Wins(after) && (human | after) != Full) HumanTurn(human, after);
    }
}

void HumanTurn(int human, int computer)
{
    for (int bit = 1; bit <= Full; bit <<= 1)
    {
        if (((human | computer) & bit) != 0) continue;
        int after = human | bit;
        if (!Wins(after) && (after | computer) != Full) ComputerTurn(after, computer);
    }
}

ComputerTurn(0, 0);   // the computer moves first
HumanTurn(0, 0);      // the human moves first

string path = args.FirstOrDefault(a => !a.StartsWith("--")) ?? "TicTacToeTable.cs";
bool masm = path.EndsWith(".asm", StringComparison.OrdinalIgnoreCase);
bool stateMachine = args.Contains("--state-machine");
if (stateMachine && !masm) throw new InvalidOperationException("--state-machine only writes assembler (.asm) data");

var sb = new StringBuilder();
string comment = masm ? "; " : "    // ";
sb.AppendLine($"{comment}BEGIN TABLE (generated by GenTable.cs - do not edit by hand)");
if (stateMachine)
{
    // The game as a finite-state machine, for programs that carry a state number instead of
    // re-reading the board. A "computer state" is a position with the computer to move (the same
    // positions as the table, numbered in sorted order, so state 0 is the empty board). For each
    // one the computer picks a best move, which leads to a "human state", and each human reply
    // leads to the next computer state. Human states are numbered in rows of nine replies:
    //   cstates[s] = firstHumanState << 9 | bestMoves
    //   human state for move m = firstHumanState + (number of best moves below m)
    //   cnext[humanState * 9 + reply] = next computer state, or 0xFFFF when the game is over
    // One extra row, HSTART, holds the nine openings for when the human moves first.
    var ids = table.Keys.Select((key, i) => (key, i)).ToDictionary(x => x.key, x => x.i);
    var cstates = new List<uint>();
    var rows = new List<ushort[]>();
    foreach (var (key, bestMoves) in table)
    {
        int human = key & Full, computer = key >> 9;
        cstates.Add((uint)rows.Count << 9 | (uint)bestMoves);
        for (int bit = 1; bit <= Full; bit <<= 1)
        {
            if ((bestMoves & bit) == 0) continue;
            int after = computer | bit;
            var row = new ushort[9];
            Array.Fill(row, (ushort)0xFFFF);
            if (!Wins(after) && (human | after) != Full)
                for (int reply = 0; reply < 9; reply++)
                {
                    int replyBit = 1 << reply;
                    if (((human | after) & replyBit) != 0) continue;
                    int nextHuman = human | replyBit;
                    if (Wins(nextHuman) || (nextHuman | after) == Full) continue;
                    row[reply] = (ushort)ids[nextHuman | after << 9];   // throws if a position is missing
                }
            rows.Add(row);
        }
    }
    int hstart = rows.Count;
    var opening = new ushort[9];
    for (int m = 0; m < 9; m++) opening[m] = (ushort)ids[1 << m];
    rows.Add(opening);

    sb.AppendLine($"{comment}{cstates.Count} computer states, {rows.Count} rows of human replies.");
    bool first = true;
    foreach (var chunk in cstates.Chunk(8))
    {
        sb.AppendLine((first ? "cstates   DWORD " : "          DWORD ") + string.Join(", ", chunk.Select(v => $"0{v:X}h")));
        first = false;
    }
    first = true;
    foreach (var chunk in rows.SelectMany(r => r).Chunk(9))
    {
        sb.AppendLine((first ? "cnext     WORD " : "          WORD ") + string.Join(", ", chunk.Select(v => $"0{v:X}h")));
        first = false;
    }
    sb.AppendLine($"HSTART EQU {hstart}");
}
else
    sb.AppendLine($"{comment}{table.Count} positions, sorted by position so they can be binary searched.");
if (stateMachine)
{
    // already written above
}
else if (masm)
{
    // MASM wants hex numbers to start with a digit and end in h.
    string Dword(KeyValuePair<int, int> e) => $"0{(uint)(e.Key << 9 | e.Value):X}h";
    bool first = true;
    foreach (var chunk in table.Chunk(8))
    {
        sb.AppendLine((first ? "entries   DWORD " : "          DWORD ") + string.Join(", ", chunk.Select(Dword)));
        first = false;
    }
    sb.AppendLine($"ENTRY_COUNT EQU {table.Count}");
}
else
{
    sb.AppendLine("    static ReadOnlySpan<uint> Entries =>");
    sb.AppendLine("    [");
    foreach (var chunk in table.Chunk(8))
        sb.AppendLine("        " + string.Join(", ", chunk.Select(e => $"0x{(uint)(e.Key << 9 | e.Value):X}")) + ",");
    sb.AppendLine("    ];");
}
sb.Append($"{comment}END TABLE");

string source = File.ReadAllText(path);
var marker = new Regex(Regex.Escape(comment) + @"BEGIN TABLE.*?" + Regex.Escape(comment) + "END TABLE", RegexOptions.Singleline);
if (!marker.IsMatch(source)) throw new InvalidOperationException($"No BEGIN/END TABLE markers in {path}");
File.WriteAllText(path, marker.Replace(source, _ => sb.ToString()));
Console.WriteLine($"Wrote {table.Count} positions to {path}");
