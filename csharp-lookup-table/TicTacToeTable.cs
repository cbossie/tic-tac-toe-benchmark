    public static int ComputerMove(int human, int computer)
    {
        uint position = (uint)(human | computer << 9);
        var entries = Entries;
        int lo = 0, hi = entries.Length - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) >> 1;
            uint entry = entries[mid];
            uint key = entry >> 9;
            if (key == position) return PickOne((int)(entry & Full));
            if (key < position) lo = mid + 1; else hi = mid - 1;
        }
        throw new InvalidOperationException($"No stored answer for position {human:X}/{computer:X}");
    }

    // Uniformly random choice among the set bits of bestMoves.
    static int PickOne(int bestMoves)
    {
        int pick = Random.Shared.Next(BitOperations.PopCount((uint)bestMoves));
        for (; pick > 0; pick--) bestMoves &= bestMoves - 1;
        return BitOperations.TrailingZeroCount(bestMoves);
    }

    public static string Render(int human, int computer)
    {
        Span<char> sq = stackalloc char[9];
        for (int i = 0; i < 9; i++)
            sq[i] = (human >> i & 1) != 0 ? 'X' : (computer >> i & 1) != 0 ? 'O' : (char)('1' + i);
        return $"\n {sq[0]} | {sq[1]} | {sq[2]} \n---+---+---\n {sq[3]} | {sq[4]} | {sq[5]} \n---+---+---\n {sq[6]} | {sq[7]} | {sq[8]} \n\n";
    }
