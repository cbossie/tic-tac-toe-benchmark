    lea     rcx, tStart
    call    QueryPerformanceCounter
    mov     ebx, 199
later:
    call    RunOpenings
    dec     ebx
    jnz     later
    lea     rcx, tEnd
    call    QueryPerformanceCounter

    mov     rax, tCold
    lea     rcx, sFirst
    mov     r8d, 9
    call    Report
    mov     rax, tEnd
    sub     rax, tStart
    lea     rcx, sLater
    mov     r8d, 1791                       ; 9 * 199
    call    Report
    add     rsp, 32
    pop     rbx
    ret
Bench endp

; ---------------------------------------------------------------- startup
Init proc
    sub     rsp, 40
    mov     ecx, -11                        ; STD_OUTPUT_HANDLE
    call    GetStdHandle
    mov     hOut, rax
    mov     ecx, -10                        ; STD_INPUT_HANDLE
    call    GetStdHandle
    mov     hIn, rax

    lea     r9, wins                        ; build the win table
    lea     r10, lines
    xor     ecx, ecx
maskloop:
    cmp     ecx, 512
    jae     seeded
    xor     edx, edx
lineloop:
    cmp     edx, 8
    jae     nextmask
    mov     eax, [r10+rdx*4]
    mov     r8d, ecx
    and     r8d, eax
    cmp     r8d, eax
    jne     nextline
    mov     byte ptr [r9+rcx], 1
nextline:
    inc     edx
    jmp     lineloop
nextmask:
    inc     ecx
    jmp     maskloop
seeded:
    rdtsc                                   ; seed the generator from the time stamp counter
    shl     rdx, 32
    or      rax, rdx
    mov     rdx, 9E3779B97F4A7C15h
    imul    rax, rdx
    or      rax, 1
    mov     rng, rax
    add     rsp, 40
    ret
Init endp

HasBench proc                               ; eax = 1 when "--bench" is on the command line
    sub     rsp, 40
    call    GetCommandLineA
    mov     rcx, rax
scan:
    cmp     byte ptr [rcx], 0
    je      absent
    lea     rdx, sBench
    xor     r8d, r8d
cmpchar:
    movzx   eax, byte ptr [rdx+r8]
    test    al, al
    jz      present
    cmp     al, [rcx+r8]
    jne     nextpos
    inc     r8
    jmp     cmpchar
nextpos:
    inc     rcx
    jmp     scan
present:
    mov     eax, 1
    jmp     quitp
absent:
    xor     eax, eax
quitp:
    add     rsp, 40
    ret
HasBench endp

main proc
    sub     rsp, 40
    call    Init
    call    HasBench
    test    eax, eax
    jz      game
    call    Bench
    jmp     quit
game:
    lea     rcx, sTitle
    call    PutStr
again:
    call    PlayGame
    lea     rcx, sAgain
    call    PutStr
    call    ReadLine
    test    eax, eax
    jle     quit
    movzx   eax, linebuf
    or      al, 20h
    cmp     al, 'y'
    je      again
quit:
    call    Flush
    xor     ecx, ecx
    call    ExitProcess
main endp

