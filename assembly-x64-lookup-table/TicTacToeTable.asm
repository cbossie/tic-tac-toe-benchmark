    test    eax, eax
    jz      eof
    cmp     nread, 0
    je      eof
    movzx   eax, byteBuf
    cmp     al, 10
    je      done
    cmp     al, 13
    je      more
    cmp     al, 32
    je      more
    cmp     al, 9
    je      more
