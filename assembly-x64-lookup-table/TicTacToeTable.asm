; ---------------------------------------------------------------- random numbers
RandBelow proc                              ; ecx = n; returns eax in [0, n); xorshift64
    lea     r8, rng
    mov     rax, [r8]
    mov     rdx, rax
    shl     rdx, 13
    xor     rax, rdx
    mov     rdx, rax
    shr     rdx, 7
    xor     rax, rdx
    mov     rdx, rax
    shl     rdx, 17
    xor     rax, rdx
    mov     [r8], rax
