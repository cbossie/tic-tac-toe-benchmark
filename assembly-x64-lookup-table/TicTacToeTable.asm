PutStr proc                                 ; rcx = zero-terminated string; clobbers rax, rdx, r8
    lea     r8, outbuf
    mov     eax, outlen
next:
    mov     dl, [rcx]
    test    dl, dl
    jz      done
    mov     [r8+rax], dl
    inc     rax
    inc     rcx
    jmp     next
done:
    mov     outlen, eax
    ret
PutStr endp

PutUInt proc                                ; rcx = unsigned value, printed in decimal
    push    rbx
    push    rsi
    sub     rsp, 24
    mov     rax, rcx
    lea     rsi, [rsp+23]
    xor     ebx, ebx
    mov     r9d, 10
