; ---------------------------------------------------------------- the stored answers
; ecx = human squares, edx = computer squares; returns the computer's move (0-8) in eax.
ComputerMove proc
    push    rbx
    mov     r8d, edx                        ; position = human | computer << 9
    shl     r8d, 9
    or      r8d, ecx
    lea     r9, entries
    xor     r10d, r10d                      ; lo
    mov     r11d, ENTRY_COUNT - 1           ; hi
search:
    cmp     r10d, r11d
    jg      missing
    lea     eax, [r10+r11]
    shr     eax, 1                          ; mid
    mov     edx, [r9+rax*4]
    mov     ecx, edx
    shr     ecx, 9                          ; the entry's position
    cmp     ecx, r8d
    je      found
    jb      goright
    lea     r11d, [rax-1]
    jmp     search
goright:
    lea     r10d, [rax+1]
    jmp     search
found:
    mov     ebx, edx                        ; the stored set of best moves
    and     ebx, 511
    popcnt  ecx, ebx                        ; choose uniformly among them
    call    RandBelow
    mov     ecx, eax
dropbit:
    test    ecx, ecx
    jz      dropped
    lea     eax, [rbx-1]
    and     ebx, eax
    dec     ecx
    jmp     dropbit
dropped:
    bsf     eax, ebx
    pop     rbx
    ret
missing:                                    ; cannot happen: every reachable position is stored
    mov     ecx, 2
    sub     rsp, 40
    call    ExitProcess
ComputerMove endp

