; ---------------------------------------------------------------- input
; Reads one line from stdin into linebuf (spaces, tabs and CR dropped, zero-terminated).
; Returns its length, or -1 at end of input.
ReadLine proc
    push    rbx
    push    rsi
    sub     rsp, 56
    call    Flush
    xor     esi, esi
